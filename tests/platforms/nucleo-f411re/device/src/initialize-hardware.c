#include <cmsis-plus/rtos/os-hooks.h>
#include <cmsis_device.h>

#include "gpio.h"

// ----------------------------------------------------------------------------

// Generated by STM32CubeMX in `main.c`; not declared in `main.h`.
extern void
SystemClock_Config (void);

// ----------------------------------------------------------------------------

// This is the application hardware initialisation routine,
// redefined to add more inits.
//
// Called early from _start(), right after data & bss init, before
// constructors.
//
// After Reset the Cortex-M processor is in Thread mode,
// priority is Privileged, and the Stack is set to Main.
//
// Warning: The HAL requires the system timer, running at 1000 Hz
// and calling HAL_IncTick().

void
os_startup_initialize_hardware (void)
{
  // Same order as the STM32CubeMX `main()`: the HAL must be initialised
  // before any other HAL function, and the clock configuration uses
  // HAL globals, so it cannot run before DATA & BSS init.
  HAL_Init ();

  // Switch to the configured clocks; HAL_RCC_ClockConfig() also
  // reprograms SysTick for the new frequency.
  SystemClock_Config ();

  // Call the CMSIS system clock routine to store the clock frequency
  // in the SystemCoreClock global RAM location.
  SystemCoreClockUpdate ();

  MX_GPIO_Init ();
}

